def enrich_speaker_notes(slides):
    """Keep operational cues and provide the same copy to HTML and Markdown."""
    for slide in slides:
        entry = LESSONS[slide['title']]
        original = re.sub(r'^【[^】]+】', '', slide['notes']).strip()
        slide['speaker_script'] = entry['script']
        slide['speaker_supplement'] = (
            '【概念、生活类比与业务实例】\n' + entry['explanation']
            + '\n\n【常见误区】\n' + entry['misconception']
            + '\n\n【互动与停顿】\n' + entry['interaction']
            + '\n\n【演示操作与原有备课提示】\n' + original)
        # Also include known terms in the read-aloud script and original cues.
        # Word boundaries keep code identifiers such as ReviewCode distinct.
        term_ids = list(entry['terms'])
        text = slide['speaker_script'] + '\n' + slide['speaker_supplement']
        for key, term in GLOSSARY.items():
            if key not in term_ids and re.search(
                    r'(?<![A-Za-z0-9_])' + re.escape(term['label']) + r'(?![A-Za-z0-9_])',
                    text, flags=re.IGNORECASE):
                term_ids.append(key)
        slide['terms'] = [{'id': key, **GLOSSARY[key]} for key in term_ids]
        slide['notes'] = ('【现场讲稿】\n' + slide['speaker_script']
                          + '\n\n【按需展开；不必逐段全部朗读】\n' + slide['speaker_supplement'])
